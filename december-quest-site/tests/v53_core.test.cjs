/* run in Node: node tests/v53_core.test.cjs */
'use strict';
const assert=require('node:assert/strict');
const C=require('../v5-core.js');
let count=0;
const T=(name,cb)=>{cb();count++;};
const settings={stake:1000,price:350};
const leg=(id,home,away,odd=2,p=60,market='Тотал')=>({id,fixtureId:id,home,away,kickoff:'2026-12-08T22:00',enabled:true,odds:odd,prob:p,market,pick:'ТБ2.5',status:'pending'});
const A=leg('a','Inter','Genoa'),B=leg('b','Roma','Napoli');
const t={date:'2026-12-08',purchased:true,mode:'original',independenceReviewed:true,legs:[A,B]};
T('independent',()=>assert.ok(C.independent([A,B])));
T('swapped same event',()=>assert.equal(C.independent([A,leg('c','Genoa','Inter')]),false));
T('different id same event',()=>assert.equal(C.independent([A,leg('d','Inter','Genoa')]),false));
T('same id different names',()=>assert.equal(C.independent([A,leg('a','Napoli','Roma')]),false));
T('accent normalization',()=>assert.equal(C.independent([leg('e','Deportivo Alavés','Espanyol'),leg('f','Espanyol','Deportivo Alaves')]),false));
T('missing teams',()=>assert.equal(C.independent([{fixtureId:'a',kickoff:'2026-12-08T22:00'}]),false));
T('edge EV paid',()=>assert.equal(C.scenario(t,settings).ev,90));
T('model P 36%',()=>assert.equal(C.scenario(t,settings).model,.36));
T('aggregate odds 4',()=>assert.equal(C.scenario(t,settings).odds,4));
T('net negative despite edge',()=>assert.equal(C.scenario({...t,legs:[A]},settings).ev,-150));
T('fee gate negative',()=>assert.equal(C.feeGate({...t,legs:[A]},settings).ok,false));
T('fee issue explicit',()=>assert.ok(C.legAudit({...t,legs:[A]},settings)[0].issues.some(x=>x.includes('чистый EV'))));
T('unreviewed independence blocks EV',()=>assert.equal(C.scenario({...t,independenceReviewed:false},settings).ev,null));
T('duplicate blocks EV',()=>assert.equal(C.scenario({...t,legs:[A,leg('z','Genoa','Inter')]},settings).ev,null));
T('missing model blocks EV',()=>assert.equal(C.scenario({...t,legs:[leg('a','Inter','Genoa',2,null)]},settings).ev,null));
T('missing quote blocks EV',()=>assert.equal(C.scenario({...t,legs:[leg('a','Inter','Genoa',null,60)]},settings).ev,null));
T('pass with tip fee',()=>assert.equal(C.scenario({mode:'pass',purchased:true,legs:[]},settings).ev,-350));
T('pass no tip fee',()=>assert.equal(C.scenario({mode:'pass',purchased:false,legs:[]},settings).ev,0));
T('p break-even 67.5',()=>assert.equal(C.sensitivity(60,2,settings).breakEvenP,67.5));
T('P lower EV -250',()=>assert.equal(C.sensitivity(60,2,settings).lowEV,-250));
T('P higher EV -50',()=>assert.equal(C.sensitivity(60,2,settings).highEV,-50));
T('no ref gate',()=>assert.ok(C.legAudit({...t,legs:[leg('a','Inter','Genoa',1.8,70,'ЖК')]},settings)[0].issues.some(x=>x.includes('Referee Gate'))));
T('market compare net',()=>assert.equal(C.marketCompare([{market:'Тотал',odds:2,prob:60}],settings)[0].ev,-150));
T('empty calibration',()=>assert.equal(C.calibration({tours:{}}).brier,null));
T('empty log loss',()=>assert.equal(C.calibration({tours:{}}).logLoss,null));
T('source https',()=>assert.ok(C.checkedUrl('https://www.uefa.com/fixture')));
T('source javascript blocked',()=>assert.equal(C.checkedUrl('javascript:alert(1)'),false));
T('no source ready',()=>assert.ok(C.cardReadiness({}, {timing_status:'confirmed'}).complete<2));
const closed={state:'closed',sealedAt:'2026-12-07T20:00:00Z',serverSealId:'',sealedSnapshot:JSON.stringify({legs:[{...A,prob:70}]}),legs:[{...A,status:'win'}]};
T('calibration one bin',()=>assert.equal(C.calibration({tours:{'2026-12-08':closed}}).n,1));
T('calibration Brier .09',()=>assert.equal(C.calibration({tours:{'2026-12-08':closed}}).brier,.09));
T('calibration log loss',()=>assert.ok(C.calibration({tours:{'2026-12-08':closed}}).logLoss>.35));
T('calibration excludes late',()=>assert.equal(C.calibration({tours:{'2026-12-08':{...closed,sealedAt:'2026-12-08T22:00:00+02:00'}}}).n,0));
T('calibration excludes push',()=>assert.equal(C.calibration({tours:{'2026-12-08':{...closed,legs:[{...A,status:'return'}]}}}).n,0));
if(typeof console!=='undefined')console.log('PASS '+count+'/'+count);
