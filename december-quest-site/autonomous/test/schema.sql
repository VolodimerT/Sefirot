CREATE OR REPLACE FUNCTION public.dq_autoforecast_prematch_guard()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO ''
AS $function$
BEGIN
 IF NEW.kickoff <= statement_timestamp() THEN
   RAISE EXCEPTION 'FORECAST_CANNOT_BE_WRITTEN_AFTER_KICKOFF' USING ERRCODE='23514';
 END IF;
 IF TG_TABLE_NAME='sefirot_december_quest_auto_forecasts' THEN
   IF NEW.source_cutoff>=NEW.kickoff THEN
    RAISE EXCEPTION 'FUTURE_LEAKAGE_BLOCKED' USING ERRCODE='23514';
   END IF;
 END IF;
 RETURN NEW;
END;
$function$
;
